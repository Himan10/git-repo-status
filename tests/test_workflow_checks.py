class ParseWorkflow(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.w = workflow_parser.parse_workflow(WORKFLOW)
        assert cls.w["parse_error"] is None, cls.w["parse_error"]
        cls.codes = [c for c, _, _ in cls.w["script"]]

    def test_uses(self):
        by_target = {u["target"]: u for u in self.w["uses"]}
        self.assertEqual(by_target["actions/checkout"]["ref_type"], "floating")
        node = by_target["actions/setup-node"]
        self.assertEqual((node["ref_type"], node["version_comment"]), ("sha", "v4.2.0"))
        self.assertEqual(by_target["org/shared/.github/workflows/release.yml"]["kind"], "reusable")
        self.assertEqual(by_target["alpine:3.20"]["kind"], "docker")

    def test_images(self):
        imgs = {i["image"]: i["digest"] for i in self.w["images"]}
        self.assertFalse(imgs["node:20"])
        self.assertTrue(imgs[f"postgres@sha256:{'c' * 64}"])
        self.assertFalse(imgs["alpine:3.20"])

    def test_script_checks(self):
        for code in ("CURL_PIPE_SHELL", "UNPINNED_PIP", "GO_INSTALL_LATEST", "SECRET_ENCODED", "XTRACE_WITH_SECRETS"):
            self.assertIn(code, self.codes)
        pip = next(d for c, _, d in self.w["script"] if c == "UNPINNED_PIP")
        self.assertEqual(pip, "pip install requests")  # black is pinned, pip itself is ignored

    def test_exfil_only_to_unknown_hosts(self):
        exfil = [(where, d) for c, where, d in self.w["script"] if c == "EXFIL_PATTERN"]
        self.assertEqual(len(exfil), 1, exfil)  # not api.github.com, not a webhook URL taken from a secret
        self.assertIn("collector.evil.example", exfil[0][1])

    def test_ai_agent_and_triggers(self):
        self.assertEqual(self.w["ai_agents"][0]["action"], "anthropics/claude-code-action")
        self.assertEqual(self.w["untrusted_triggers"], ["issue_comment"])
        self.assertEqual(self.w["secrets"], ["DEPLOY_KEY", "GH_PAT", "SLACK_WEBHOOK"])

    def test_broken_yaml(self):
        w = workflow_parser.parse_workflow("on: [push\njobs: {")
        self.assertTrue(w["parse_error"])
        self.assertEqual(w["uses"], [])


